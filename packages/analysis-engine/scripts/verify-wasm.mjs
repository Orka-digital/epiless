import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { execFile } from 'node:child_process';
import { constants } from 'node:fs';
import { access, mkdtemp, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { promisify } from 'node:util';

const execute = promisify(execFile);
const engineRoot = fileURLToPath(new URL('../', import.meta.url));
const hash = (
  /** @type {NonSharedBuffer | import("crypto").BinaryLike} */ bytes,
) => createHash('sha256').update(bytes).digest('hex');
const compilerArguments = [
  '--target=wasm32-unknown-unknown',
  '-O3',
  '-fno-fast-math',
  '-ffp-contract=off',
  '-fno-builtin',
  '-nostdlib',
  '-fuse-ld={linker}',
  '-Wl,--no-entry,--import-memory,--export=process_dense,--export=__heap_base,--stack-first,-z,stack-size=65536,--initial-memory=131072,--max-memory=268435456,--strip-all',
  '{source}',
  '-o',
  '{output}',
];
const expectedExports = [
  { name: '__heap_base', kind: 'global' },
  { name: 'kernel_abi_version', kind: 'function' },
  { name: 'kernel_state_size', kind: 'function' },
  { name: 'process_dense', kind: 'function' },
];

/**
 * @param {string} command
 */
async function executable(command) {
  const candidates = command.includes(path.sep)
    ? [path.resolve(command)]
    : (process.env.PATH ?? '')
        .split(path.delimiter)
        .map((directory) => path.resolve(directory, command));
  for (const candidate of candidates) {
    try {
      await access(candidate, constants.X_OK);
      // Keep the wasm-ld symlink name: LLD selects its driver from argv[0].
      return candidate;
    } catch {
      // Try the next PATH entry; no tools are installed or downloaded here.
    }
  }
  throw new Error(
    `Cannot find ${command}; set EPILESS_WASM_CLANG and EPILESS_WASM_LINKER to LLVM 23.1.4 executables.`,
  );
}

/** Check committed source/bytes/ABI without requiring a compiler. This catches
 * stale files; only --rebuild proves that the pinned compiler produces them. */
export async function verifyDenseKernel({ rebuild = false } = {}) {
  const manifest = JSON.parse(
    (
      await readFile(
        path.join(engineRoot, 'src/wasm/kernel-manifest.json'),
        'utf8',
      )
    ).toString(),
  );
  assert.equal(manifest.version, 1, 'Unsupported kernel manifest');
  assert.deepEqual(manifest.abi, { version: 2, stateBytes: 100, pointers: 25 });
  assert.equal(manifest.source.path, 'src/wasm/dense.c');
  assert.equal(manifest.generated.path, 'src/dense-kernel.generated.ts');
  assert.equal(manifest.toolchain.version, '23.1.4');
  assert.deepEqual(
    manifest.compilerArguments,
    compilerArguments,
    'Unreviewed kernel compiler flags',
  );
  const source = await readFile(path.join(engineRoot, manifest.source.path));
  assert.equal(
    hash(source),
    manifest.source.sha256,
    'Kernel C source changed without a matching manifest/binary',
  );
  const generated = await readFile(
    path.join(engineRoot, manifest.generated.path),
    'utf8',
  );
  // Parse the one generated decimal array, without importing or evaluating TS.
  const plain = generated.replace(/\/\*[\s\S]*?\*\/|\/\/[^\r\n]*/g, '').trim();
  const match =
    /^export\s+const\s+DENSE_KERNEL_BYTES\s*=\s*new\s+Uint8Array\s*\(\s*\[([\d\s,]*)\]\s*\)\s*;?$/.exec(
      plain,
    );
  assert.ok(
    match,
    'Generated kernel must contain only the literal DENSE_KERNEL_BYTES byte array',
  );
  const tokens = match[1].trim().replace(/,\s*$/, '').split(',');
  assert.ok(
    tokens.length > 0 && tokens.length <= 65536,
    'Unexpected dense-kernel size',
  );
  const numbers = tokens.map((token) => {
    assert.match(
      token.trim(),
      /^(?:0|[1-9]\d{0,2})$/,
      'Invalid generated byte',
    );
    const value = Number(token);
    assert.ok(value <= 255, 'Generated byte exceeds 255');
    return value;
  });
  const bytes = Uint8Array.from(numbers);
  assert.equal(
    bytes.length,
    manifest.generated.bytes,
    'Kernel byte count changed',
  );
  assert.equal(
    hash(bytes),
    manifest.generated.sha256,
    'Generated kernel bytes changed without a matching manifest',
  );
  const module = new WebAssembly.Module(bytes);
  assert.deepEqual(
    WebAssembly.Module.imports(module),
    [{ module: 'env', name: 'memory', kind: 'memory' }],
    'Kernel must import only its local memory',
  );
  assert.deepEqual(
    WebAssembly.Module.exports(module).sort((a, b) =>
      a.name.localeCompare(b.name, 'en'),
    ),
    expectedExports,
    'Unexpected kernel exports',
  );
  const memory = new WebAssembly.Memory({ initial: 2, maximum: 4096 });
  const instance = new WebAssembly.Instance(module, { env: { memory } });
  assert.ok(typeof instance.exports.kernel_abi_version === 'function');
  assert.ok(typeof instance.exports.kernel_state_size === 'function');
  assert.ok(instance.exports.__heap_base instanceof WebAssembly.Global);
  assert.equal(instance.exports.kernel_abi_version(), 2);
  assert.equal(instance.exports.kernel_state_size(), 100);
  const heapBase = Number(instance.exports.__heap_base.value);
  assert.ok(
    Number.isInteger(heapBase) &&
      heapBase >= 65536 &&
      heapBase <= memory.buffer.byteLength,
    'Invalid kernel stack/static allocation',
  );
  const result = {
    check: rebuild
      ? 'PINNED_COMPILER_BYTE_REBUILD'
      : 'SOURCE_BINARY_COHERENCE_AND_ABI',
    sourceSha256: manifest.source.sha256,
    binarySha256: manifest.generated.sha256,
    bytes: bytes.length,
    abiVersion: 2,
    stateSize: 100,
    compilerRebuilt: false,
  };
  if (!rebuild) return result;

  const clang = await executable(process.env.EPILESS_WASM_CLANG ?? 'clang');
  const linker = await executable(process.env.EPILESS_WASM_LINKER ?? 'wasm-ld');
  const clangVersion = (await execute(clang, ['--version'])).stdout.trim();
  const linkerVersion = (await execute(linker, ['--version'])).stdout.trim();
  assert.match(
    clangVersion,
    /\bclang version 23\.1\.4\b/,
    'Rebuild requires clang 23.1.4',
  );
  assert.match(
    linkerVersion,
    /\bLLD 23\.1\.4\b/,
    'Rebuild requires wasm-ld 23.1.4',
  );
  const directory = await mkdtemp(
    path.join(tmpdir(), 'epiless-kernel-rebuild-'),
  );
  try {
    const output = path.join(directory, 'dense.wasm');
    const args = compilerArguments.map((argument) =>
      argument
        .replace('{linker}', linker)
        .replace('{source}', path.join(engineRoot, manifest.source.path))
        .replace('{output}', output),
    );
    await execute(clang, args, { cwd: engineRoot, timeout: 60000 });
    const rebuilt = await readFile(output);
    assert.deepEqual(
      rebuilt,
      Buffer.from(bytes),
      'Pinned compiler output differs from the committed kernel; do not refresh the manifest without differential and native validation',
    );
    return { ...result, compilerRebuilt: true, clangVersion, linkerVersion };
  } finally {
    await rm(directory, { recursive: true, force: true });
  }
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href
) {
  const args = process.argv.slice(2);
  if (args.some((argument) => argument !== '--rebuild') || args.length > 1)
    throw new Error('Usage: node scripts/verify-wasm.mjs [--rebuild]');
  console.log(
    JSON.stringify(
      await verifyDenseKernel({ rebuild: args.includes('--rebuild') }),
      null,
      2,
    ),
  );
}
